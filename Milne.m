clc;
clear;

f = @(x,y) x.^3 + y;

h = 0.2;

x = [0 0.2 0.4 0.6];
y = [2 2.073 2.452 3.023];

f0 = f(x(1), y(1));
f1 = f(x(2), y(2));
f2 = f(x(3), y(3));
f3 = f(x(4), y(4));

yp = y(1) + (4*h/3)*(2*f1 - f2 + 2*f3);

f4p = f(0.8, yp);

y4 = y(3) + (h/3)*(f2 + 4*f3 + f4p);

disp(y4);